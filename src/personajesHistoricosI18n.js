// Traduce `es` al idioma `lang` usando el diccionario empaquetado.
// Si no hay traducción (nombres propios, pistas personalizadas…), devuelve `es`.
// NUNCA llama a Gemini.
export function trPH(lang, es) {
    if (!lang || lang === 'es' || typeof es !== 'string') return es;
    const dic = PH_I18N[lang];
    return (dic && dic[es] !== undefined) ? dic[es] : es;
}
